"""Downstream phylogenomic tree-inference script generation (RAxML-NG / IQ-TREE 2)."""

from __future__ import annotations

from pathlib import Path


def generate_tree_commands(
    matrix_path: Path,
    partition_path: Path | None,
    out_prefix: Path,
    cores: int = 1,
    data_type: str = "dna",
) -> dict[str, str]:
    """Generate CLI invocations for RAxML-NG and IQ-TREE 2.

    When ``partition_path`` points at an existing partition file, both tools
    receive that file (``--model`` / ``-p``). Otherwise an unpartitioned
    fallback model is used: ``LG+G`` for amino-acid matrices, ``GTR+G`` for DNA.
    """
    matrix_path = Path(matrix_path)
    out_prefix = Path(out_prefix)
    default_model = (
        "LG+G" if str(data_type).lower() in {"aa", "protein", "prot"} else "GTR+G"
    )
    if partition_path is not None and Path(partition_path).is_file():
        part = Path(partition_path)
        raxml_model_arg = f"--model {part}"
        iqtree_model_arg = f"-p {part}"
    else:
        raxml_model_arg = f"--model {default_model}"
        iqtree_model_arg = f"-m {default_model}"
    return {
        "raxml_ng": (
            f"raxml-ng --msa {matrix_path} {raxml_model_arg} "
            f"--prefix {out_prefix}_raxml --threads {cores} --seed 42 --all"
        ),
        "iqtree2": (
            f"iqtree2 -s {matrix_path} {iqtree_model_arg} "
            f"--prefix {out_prefix}_iqtree -T {cores} -B 1000 --alrt 1000"
        ),
    }


def write_tree_runner_scripts(
    out_dir: Path,
    matrix_path: Path,
    partition_path: Path | None,
    cores: int = 1,
    data_type: str = "dna",
) -> dict[str, Path]:
    """Write executable ``run_raxml_ng.sh`` / ``run_iqtree2.sh`` beside outputs."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_prefix = out_dir / "tree"
    commands = generate_tree_commands(
        matrix_path=matrix_path,
        partition_path=partition_path,
        out_prefix=out_prefix,
        cores=cores,
        data_type=data_type,
    )
    written: dict[str, Path] = {}
    script_configs = (
        ("raxml_ng", out_dir / "run_raxml_ng.sh"),
        ("iqtree2", out_dir / "run_iqtree2.sh"),
    )
    for key, script_path in script_configs:
        content = (
            "#!/usr/bin/env bash\n"
            "set -euo pipefail\n\n"
            "# Generated by PlastBurstAlign for downstream phylogenetic inference\n"
            f"{commands[key]}\n"
        )
        script_path.write_text(content, encoding="utf-8")
        script_path.chmod(script_path.stat().st_mode | 0o111)
        written[key] = script_path
    return written


def resolve_matrix_path(
    out_dir: Path,
    written: dict[str, str] | None = None,
) -> Path | None:
    """Prefer concat FASTA, then PHYLIP, then NEXUS from ``write_all`` metadata."""
    written = written or {}
    for key in ("fasta", "phylip", "nexus"):
        candidate = written.get(key)
        if candidate and Path(candidate).is_file():
            return Path(candidate)

    out_dir = Path(out_dir)
    for pattern in (
        "nucl_*concat.aligned.fasta",
        "*concat.aligned.fasta",
        "nucl_*concat.aligned.phy",
        "*concat.aligned.phy",
        "nucl_*concat.aligned.nexus",
        "*concat.aligned.nexus",
    ):
        hits = sorted(out_dir.glob(pattern))
        if hits:
            return hits[0]
    return None


def resolve_partition_path(
    out_dir: Path,
    written: dict[str, str] | None = None,
) -> Path | None:
    """Prefer RAxML-NG ``*.partitions.txt``, then IQ-TREE alias sidecars."""
    written = written or {}
    for key in ("raxml", "iqtree"):
        candidate = written.get(key)
        if candidate and Path(candidate).is_file():
            return Path(candidate)

    out_dir = Path(out_dir)
    for pattern in (
        "nucl_*concat.partitions.txt",
        "*concat.partitions.txt",
        "nucl_*concat.partitions.iqtree.txt",
        "*concat.partitions.iqtree.txt",
        "*.partitions.txt",
        "*.partitions.iqtree.txt",
    ):
        hits = sorted(out_dir.glob(pattern))
        if hits:
            return hits[0]
    return None


def coerce_tree_cores(num_threads: object, default: int = 1) -> int:
    """Coerce ``num_threads`` (int or ``\"auto\"``) to a positive core count."""
    if num_threads is None:
        return max(1, int(default))
    if isinstance(num_threads, bool):
        return max(1, int(default))
    if isinstance(num_threads, int):
        return max(1, num_threads)
    if isinstance(num_threads, float):
        return max(1, int(num_threads))
    if isinstance(num_threads, str):
        cleaned = num_threads.strip().lower()
        if cleaned == "auto" or cleaned == "":
            return max(1, int(default))
        try:
            return max(1, int(cleaned))
        except ValueError:
            return max(1, int(default))
    return max(1, int(default))


def data_type_from_mode(select_mode: object) -> str:
    """Map select mode / labels to ``\"aa\"`` or ``\"dna\"`` for model defaults."""
    if select_mode is None:
        return "dna"
    value = getattr(select_mode, "value", select_mode)
    token = str(value).split(".")[-1].strip().lower()
    if token in {"prot", "aa", "protein", "amino", "aminoacid", "amino_acid"}:
        return "aa"
    return "dna"
